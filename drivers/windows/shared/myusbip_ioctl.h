#define IOCTL_MYUSBIP_EXPORTER_LIST_DEVICES  CTL_CODE(FILE_DEVICE_MYUSBIP, 0x801, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_MYUSBIP_EXPORTER_SHARE         CTL_CODE(FILE_DEVICE_MYUSBIP, 0x802, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_MYUSBIP_EXPORTER_UNSHARE       CTL_CODE(FILE_DEVICE_MYUSBIP, 0x803, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_MYUSBIP_EXPORTER_SUBMIT_URB    CTL_CODE(FILE_DEVICE_MYUSBIP, 0x804, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_MYUSBIP_EXPORTER_CANCEL_URB    CTL_CODE(FILE_DEVICE_MYUSBIP, 0x805, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_MYUSBIP_EXPORTER_GET_COMPLETION CTL_CODE(FILE_DEVICE_MYUSBIP, 0x806, METHOD_BUFFERED, FILE_ANY_ACCESS)

#define IOCTL_MYUSBIP_VHCI_GET_VERSION       CTL_CODE(FILE_DEVICE_MYUSBIP, 0x900, METHOD_BUFFERED, FILE_ANY_ACCESS)
#define IOCTL_MYUSBIP_VHCI_CREATE_PORT       CTL_CODE(FILE_DEVICE_MYUSBIP, 0x901, METHOD_BUFFERED, FILE_ANY_ACCESS)
